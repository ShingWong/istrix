# Short prefixes (first 2 bytes / 4 hex chars) for the above
# These are used as fallback when full 6-char OUI doesn't match
_SHORT_OUIS: dict[str, str] = {}
for oui, vendor in _MORE_OUIS.items():
    if len(oui) == 4:
        _SHORT_OUIS[oui] = vendor


def oui_lookup(mac_address: str) -> str:
    """Look up vendor from MAC address OUI.

    Args:
        mac_address: MAC address in any common format (xx:xx:xx:xx:xx:xx, etc.)

    Returns:
        Vendor name string or empty string if unknown.
    """
    if not mac_address:
        return ""
    clean = mac_address.replace(":", "").replace("-", "").replace(".", "").upper()
    if len(clean) < 6:
        return ""

    # Full 6-char OUI
    oui6 = clean[:6]

    # Overrides first
    if oui6 in OUI_OVERRIDES:
        return OUI_OVERRIDES[oui6]

    # Main DB
    vendor = OUI_DB.get(oui6, "")
    if vendor:
        return vendor

    # Supplementary DB
    vendor = _MORE_OUIS.get(oui6, "")
    if vendor:
        return vendor

    # Short prefix (first 4 chars)
    oui4 = clean[:4]
    vendor = _SHORT_OUIS.get(oui4, "")
    if vendor:
        return vendor

    # Locally administered MAC (bit 2 of first byte set)
    # 02, 06, 0A, 0E = locally administered for unicast
    # x2, x6, xA, xE, x3, x7, xB, xF
    first_byte = int(clean[:2], 16)
    if first_byte & 0x02:
        return "Virtual"

    return ""
